                                AuthBenefitRow(
                                    icon = Icons.Outlined.Insights,
                                    title = "Full Performance Analytics",
                                    subtitle = "Equity curves, P&L calendar, R-multiples, Edge Score, and mistake cost quantifier."
                                )
                                AuthBenefitRow(
                                    icon = Icons.Outlined.Shield,
                                    title = "Private Per-Account Vault",
                                    subtitle = "Protected by per-user Google authentication so only your account can read or edit your ledger."
                                )
                            }

                            if (authError != null) {
                                Surface(
                                    color = ext.lossContainer,
                                    shape = RoundedCornerShape(10.dp),
                                    modifier = Modifier.fillMaxWidth()
                                ) {
                                    Text(
                                        text = authError!!,
                                        style = MaterialTheme.typography.bodySmall,
                                        color = ext.onLossContainer,
                                        modifier = Modifier.padding(12.dp)
                                    )
                                }
                            }

                            Button(
                                onClick = {
                                    authError = null
                                    isSigningIn = true
                                    onGoogleSignInClicked(
                                        context = context,
                                        credentialManager = credentialManager,
                                        onAuthSuccess = {
                                            isSigningIn = false
                                            onAuthSuccess()
                                        },
                                        onAuthError = { msg ->
                                            isSigningIn = false
                                            authError = msg
                                        },
                                        scope = scope,
                                        onAuthCancelled = {
                                            isSigningIn = false
                                        }
                                    )
                                },
                                enabled = !isSigningIn && !isAutoChecking,
                                modifier = Modifier
                                    .fillMaxWidth()
                                    .height(52.dp)
                                    .testTag("google_sign_in_button"),
                                colors = ButtonDefaults.buttonColors(
                                    containerColor = MaterialTheme.colorScheme.primary,
                                    contentColor = MaterialTheme.colorScheme.onPrimary
                                )
                            ) {
                                if (isSigningIn || isAutoChecking) {
                                    CircularProgressIndicator(
                                        modifier = Modifier.size(20.dp),
                                        color = MaterialTheme.colorScheme.onPrimary,
                                        strokeWidth = 2.dp
                                    )
                                    Spacer(Modifier.width(10.dp))
                                    Text(stringResource(R.string.auth_signing_in))
                                } else {
                                    Text(
                                        text = stringResource(R.string.auth_sign_in_google),
                                        style = MaterialTheme.typography.titleSmall,
                                        fontWeight = FontWeight.Bold
                                    )
                                }
                            }
                        }
                    }
                }
            }
        }
    }
}

